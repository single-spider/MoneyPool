import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {basePath} from './base-path.mjs';
const base=basePath(), assets=(await readdir('dist/assets')).map(n=>base+'assets/'+n);
const urls=[base,base+'index.html',base+'icon.svg',base+'manifest.webmanifest',...assets];
const prefix='moneypool-'+createHash('sha256').update(base).digest('hex').slice(0,12)+'-';
const digest=createHash('sha256');
for(const path of ['index.html','icon.svg','manifest.webmanifest'])digest.update(await readFile('dist/'+path));
digest.update(JSON.stringify(assets));
const cache=prefix+digest.digest('hex').slice(0,12);
await writeFile('dist/sw.js',`const CACHE=${JSON.stringify(cache)},PREFIX=${JSON.stringify(prefix)},BASE=${JSON.stringify(base)},URLS=${JSON.stringify(urls)};
self.addEventListener('install',e=>e.waitUntil(caches.open(CACHE).then(c=>c.addAll(URLS)).then(()=>self.skipWaiting())));
self.addEventListener('activate',e=>e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith(PREFIX)&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',e=>{const r=e.request,u=new URL(r.url);if(r.method!=='GET'||u.origin!==self.location.origin||!u.pathname.startsWith(BASE))return;if(r.mode==='navigate'){e.respondWith(fetch(r).catch(()=>caches.match(BASE+'index.html')));return;}if(URLS.includes(u.pathname))e.respondWith(caches.open(CACHE).then(c=>c.match(u.pathname)).then(hit=>hit||fetch(r)));});
`);
