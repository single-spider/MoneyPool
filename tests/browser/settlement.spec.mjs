import {test,expect} from '@playwright/test';
test('settlement only affects balance after simulated recipient confirms',async({page})=>{
 await page.goto('./');
 await expect(page.locator('.notice')).toContainText('Demo workspace');
 const riya=page.locator('.item').filter({hasText:'Riya'});
 await expect(riya).toContainText('500.00');
 await riya.getByRole('button',{name:'Pay',exact:true}).click();
 await page.getByLabel('Amount (₹)').fill('200');
 await page.getByRole('button',{name:'Generate payment request'}).click();
 await expect(page.getByAltText('Non-payable demo QR code')).toBeVisible();
 await page.getByRole('button',{name:'Simulate payment'}).click();
 await page.getByRole('button',{name:'Submit payment claim'}).click();
 await expect(page.locator('.status.reported')).toBeVisible();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(riya).toContainText('500.00');
 await page.getByLabel('View as').selectOption('riya');
 await page.getByRole('button',{name:/Payments/}).click();
 await page.getByRole('button',{name:'Confirm receipt'}).click();
 await page.getByRole('button',{name:'Simulate receipt confirmation'}).click();
 await expect(page.locator('.status.confirmed')).toBeVisible();
 await page.getByLabel('View as').selectOption('me');
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(riya).toContainText('300.00');
 await page.reload();
 await expect(riya).toContainText('300.00');
});
test('add and reverse expense without erasing history',async({page})=>{
 await page.goto('./');
 await page.getByRole('button',{name:'＋ Add expense'}).click();
 await page.getByLabel('Description').fill('Groceries');
 await page.getByLabel('Amount (₹)').fill('300');
 await page.getByLabel('Category').selectOption('Food');
 await page.getByRole('button',{name:'Save expense'}).click();
 await page.getByRole('button',{name:'Activity',exact:true}).click();
 const expense=page.locator('.item').filter({hasText:'Groceries'});
 await expect(expense).toContainText('300.00');
 await expense.getByRole('button',{name:'Reverse',exact:true}).click();
 await page.getByRole('button',{name:'Reverse expense'}).click();
 await expect(expense).toContainText('Reversed');
});
